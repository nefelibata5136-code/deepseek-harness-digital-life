import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { bootNative, here } from './boot-native.mjs';
import { fixtureTransport } from './fixture-transport.mjs';
import { baselineToolNames } from './persona-plugin.mjs';
const root = resolve(here, '../../reports/task_A/integrated-' + randomUUID());
const workspace = resolve(root, 'workspace');
await mkdir(workspace, { recursive: true });
await writeFile(resolve(workspace, 'persona-core.md'), await readFile('.local/workspace/persona-core.md'));
await writeFile(resolve(workspace, 'AGENTS.md'), '# Offline fixture only\n');
await writeFile(resolve(workspace, 'audit.txt'), 'before\n');
process.env.DEEPSEEK_API_KEY = 'offline-placeholder-not-a-secret';
let sent = 0; const wires = [];
const fake = fixtureTransport(workspace);
globalThis.fetch = async (...args) => { const response = await fake.transport(...args); sent = fake.count(); wires.splice(0, wires.length, ...fake.wires); return response; };
const sessionId = randomUUID();
const ctx = await bootNative({ sessionId, testRoot: root });
try {
  await ctx.sessionController.create({ sessionId, cwd: workspace });
  const resolved = await ctx.sessionController.resolveAgent(sessionId);
  if ('error' in resolved) throw resolved.error;
  const { agent } = resolved;
  const tools = agent.ctx.tools.schemas(agent).map(tool => tool.name);
  for (const name of baselineToolNames) assert(tools.includes(name), 'Missing tool ' + name);
  const errors = [];
  ctx.on('agent/error', ({ error }) => errors.push(String(error)));
  await ctx.sessionController.prompt({ sessionId, requestId: randomUUID(), mode: 'queue', content: [{ type: 'text', text: 'Offline fixture transport validation.' }], clientTimeZone: 'Asia/Shanghai' }, new AbortController().signal);
  await agent.whenIdle();
  assert.deepEqual(errors, []);
  assert.equal(await readFile(resolve(workspace, 'audit.txt'), 'utf8'), 'after\n');
  assert.equal(sent, 3);
  assert(wires.every(body => Number.isInteger(body.max_tokens) && body.max_tokens <= 65536));
  let budget = await ctx.personaHost.status();
  assert.equal(budget.open_attempts, 0); assert.equal(budget.unknown_attempts, 0);
  const scheduled = await ctx.personaHost.schedule.create(sessionId, { title: 'Offline integration', prompt: 'Offline fixture wakeup.', at: new Date(Date.now() + 2000).toISOString() });
  await new Promise(resolve => setTimeout(resolve, 3500));
  await agent.whenIdle();
  assert.equal(sent, 4); budget = await ctx.personaHost.status();
  assert.equal(budget.open_attempts, 0); assert.equal(budget.unknown_attempts, 0);
  await ctx.sessions.flush(agent.session);
  const events = [...agent.session.ownEvents()];
  assert(events.some(event => event.type === 'tool/call'));
  assert(events.some(event => event.type === 'turn/end'));
  const history = await ctx.personaHost.schedule.history({ sessionId, id: scheduled.id, limit: 100 });
  const skillRoot = resolve(workspace, '.dsh/skills/live-fixture');
  await ctx.skills.list({ cwd: workspace });
  await mkdir(skillRoot, { recursive: true });
  await writeFile(resolve(skillRoot, 'SKILL.md'), '---\nname: live-fixture\ndescription: Offline watcher fixture.\n---\nFixture skill.\n');
  await new Promise(resolve => setTimeout(resolve, 1200));
  assert((await ctx.skills.list({ cwd: workspace })).some(skill => skill.name === 'live-fixture'));
  const versions = ctx.workspaceFoundation.run('log');
  assert(versions.log.includes('after-tool:write'));
  const result = { passed: true, observed_at: new Date().toISOString(), root, sessionId, tools, native_requests: sent,
    paid_requests: 0, formal_session_created: false, first_note_written: false, budget, schedule: scheduled, history,
    skill_discovered_without_restart: true, native_events: events.length, snapshots: versions.log, native_wire_max_tokens: wires.map(body => body.max_tokens) };
  await writeFile(resolve(here, '../../reports/task_A/integrated_validation.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify({ passed: true, root, native_requests: sent, paid_requests: 0 }));
} finally { await ctx.fiber.dispose(); }
