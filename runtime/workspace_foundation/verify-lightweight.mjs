const execute=hooks.get('tools/execute');backups.length=0;
const exec=(name,id='session-a',path='C:/fixture/a.txt')=>({name,agent:{session:{id,header:{cwd:'C:/fixture'}}},arguments:{file_path:path},signal:new AbortController().signal});
