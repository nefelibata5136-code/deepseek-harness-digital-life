releaseState();assert.equal(await first,1);assert.equal(await second,2);assert.equal(backups.length,0);
console.log(JSON.stringify({passed:true,speedPolicyVersion:versions.speedPolicyVersion,checks:['light-state-through-held-opaque-operation','control-tools-through-held-opaque-operation','read-with-zero-snapshots','same-session-state-serialized','different-session-state-independent'],paidModelCalls:0}));
